    private static void Catalog(List<string> lines, string label, IEnumerable<IndicatorCatalogItem> items, IEnumerable<CoreIndicatorCategory> categories)
    {
        lines.Add($"{label}|categories|{string.Join(",", categories)}");
        int index = 0;
        foreach (var item in items)
        {
            lines.Add($"{label}|item{index++}|{item.Type}|{item.ShortName}|{item.DisplayName}|{item.Category}");
        }
    }

    private static string Describe(Func<string> read)
    {
        try
        {
            return read();
        }
        catch (Exception ex)
        {
            return "EX:" + ex.GetType().Name;
        }
    }

    private static async Task<List<string>> CaptureDriver()
    {
        var service = new Mock<IDynamicPeriodDriverService>();
        service.Setup(s => s.GetDynamicPeriodDriversAsync()).ReturnsAsync(Array.Empty<CoreIndicatorSettings>());
        service.Setup(s => s.GetDynamicPeriodDrivers()).Returns(Array.Empty<CoreIndicatorSettings>());

        var vm = new DynamicPeriodDriverRegistrationViewModel(service.Object, IndicatorFactory.Default);
        await vm.InitializationTask;

        var lines = new List<string>();
        Catalog(lines, "driver", vm.FilteredCatalogItems.ToList(), vm.Categories.ToList());
        foreach (var item in vm.FilteredCatalogItems.ToList())
        {
            foreach (bool useShort in new[] { false, true })
            {
                vm.UseShortName = useShort;
                vm.SelectedCatalogItem = item;
                lines.Add($"driver|preview|{item.ShortName}|{useShort}|main|{Describe(() => vm.PreviewName)}");
                foreach (string output in vm.AvailableOutputs.ToList())
                {
                    vm.SelectedOutput = output;
                    lines.Add($"driver|preview|{item.ShortName}|{useShort}|{output}|{Describe(() => vm.PreviewName)}");
                }
            }
        }

        return lines;
    }

    private static async Task<List<string>> CaptureSource()
    {
        var service = new Mock<ISourceIndicatorService>();
        service.Setup(s => s.GetSourceIndicatorsAsync()).ReturnsAsync(Array.Empty<CoreIndicatorSettings>());
        service.Setup(s => s.GetSourceIndicators()).Returns(Array.Empty<CoreIndicatorSettings>());

        var vm = new SourceIndicatorRegistrationViewModel(service.Object, IndicatorFactory.Default);
        await vm.InitializationTask;

        var lines = new List<string>();
        Catalog(lines, "source", vm.FilteredCatalogItems.ToList(), vm.Categories.ToList());
        foreach (var item in vm.FilteredCatalogItems.ToList())
        {
            foreach (bool useShort in new[] { false, true })
            {
                vm.UseShortName = useShort;
