/// <summary>
/// Characterization of <see cref="PriceDataHelper"/> price extraction. The expected lines were captured from the code before the
/// duplicated Heikin-Ashi / price-switch logic was folded into private primitives, and must never be edited: every value is
/// compared by its text AND by <see cref="decimal.GetBits(decimal)"/> (same digits, same scale).
/// Fixture F-OHLC8 deliberately mixes decimal scales 0, 1, 2 and 4 (row 3) so a scale change is detected.
/// </summary>
public class PriceDataHelperCharacterizationTests
{
    private readonly ITestOutputHelper _output;

    public PriceDataHelperCharacterizationTests(ITestOutputHelper output)
    {
        _output = output;
    }

    private static void AddSeries(List<string> lines, string group, PriceType type, IEnumerable<decimal?> series)
    {
        int i = 0;
        foreach (var value in series)
        {
            lines.Add($"{group}|{type}|{i++}|{Format(value)}");
        }
    }

    private static List<string> Capture()
    {
        var lines = new List<string>();
        var core = Enumerable.Range(0, Ohlc8Rows.Length).Select(Ohlc8Core).ToList();
        var plain = Enumerable.Range(0, Ohlc8Rows.Length).Select(Ohlc8Plain).ToList();

        var withNull = new List<CoreCandleData?>(core.Cast<CoreCandleData?>());
        withNull[4] = null;

        var secondaryGap = new List<CoreCandleData?>();
        for (int i = 0; i < core.Count; i++)
        {
            if (i != 2 && i != 3)
            {
                secondaryGap.Add(core[i]);
            }
        }

        var secondaryFull = new List<CoreCandleData?>(core.Cast<CoreCandleData?>());

        var argumentTuples = new (decimal? PrevClose, decimal? PrevHaOpen, decimal? PrevHaClose)[]
        {
            (null, null, null),
            (99.5m, null, null),
            (null, 100.5m, 101.25m),
        };

        foreach (PriceType type in Enum.GetValues<PriceType>())
        {
            // G1: nullable-element list, CoreCandleData
            AddSeries(lines, "G1", type, PriceDataHelper.ExtractPriceSeries(new List<CoreCandleData?>(core.Cast<CoreCandleData?>()), type));

            // G2: CandleData list
            AddSeries(lines, "G2", type, PriceDataHelper.ExtractPriceSeries(plain, type));

            // G3: non-nullable series for both candle types
            AddSeries(lines, "G3c", type, PriceDataHelper.ExtractNonNullablePriceSeries(core, type).Select(v => (decimal?)v));
            AddSeries(lines, "G3p", type, PriceDataHelper.ExtractNonNullablePriceSeries(plain, type).Select(v => (decimal?)v));

            // G4: single-candle extraction with explicit previous state
            for (int t = 0; t < argumentTuples.Length; t++)
            {
                var a = argumentTuples[t];
                CoreCandleData coreCandle = core[3];
                CandleData plainCandle = plain[3];
                lines.Add($"G4c|{type}|{t}|{Format(PriceDataHelper.ExtractPrice(coreCandle, type, a.PrevClose, a.PrevHaOpen, a.PrevHaClose))}");
                lines.Add($"G4p|{type}|{t}|{Format(PriceDataHelper.ExtractPrice(plainCandle, type, a.PrevClose, a.PrevHaOpen, a.PrevHaClose))}");
            }

            // G5: a null element inside the list
            AddSeries(lines, "G5", type, PriceDataHelper.ExtractPriceSeries(withNull, type));

            // G6: date aligned series, gap in the secondary list and the 1:1 fast path
            AddSeries(lines, "G6gap", type, PriceDataHelper.ExtractDateAlignedPriceSeries(core, secondaryGap, type));
            AddSeries(lines, "G6full", type, PriceDataHelper.ExtractDateAlignedPriceSeries(core, secondaryFull, type));
        }

        // Empty and null inputs (boundary): lengths only.
        lines.Add("E1|" + PriceDataHelper.ExtractPriceSeries((IReadOnlyList<CoreCandleData?>?)null, PriceType.Close).Count);
        lines.Add("E2|" + PriceDataHelper.ExtractPriceSeries(new List<CandleData>(), PriceType.HeikinAshiClose).Count);
        lines.Add("E3|" + PriceDataHelper.ExtractNonNullablePriceSeries((IReadOnlyList<CoreCandleData>?)null, PriceType.Close).Count);
        return lines;
    }

    [Fact]
    public void PriceExtraction_MatchesCapturedValues_ForEveryPriceTypeAndCandleType()
    {
        var actual = Capture();

        AssertMatches(Expected, actual, _output);
    }

