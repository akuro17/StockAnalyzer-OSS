    /// <summary>
    /// Characterization of every <see cref="AutoBoxSizeCalculator"/> overload. The expected lines were captured before the shared
    /// size resolution was extracted and must never be edited: each value is compared by its text and by
    /// <see cref="decimal.GetBits(decimal)"/>. Candles are the first N rows of fixture F-OHLC8 (mixed decimal scales).
    /// </summary>
    public class AutoBoxSizeCalculatorCharacterizationTests
    {
        private const int AtrPeriod = 3;
        private const decimal AtrMultiplier = 1.5m;
        private const decimal Percentage = 1.0m;

        private readonly ITestOutputHelper _output;

        public AutoBoxSizeCalculatorCharacterizationTests(ITestOutputHelper output)
        {
            _output = output;
        }

        private static List<string> Capture()
        {
            var lines = new List<string>();
            var modes = (ChartSizingMode[])Enum.GetValues(typeof(ChartSizingMode));
            var roundings = (ChartRoundingMode[])Enum.GetValues(typeof(ChartRoundingMode));
            var fallbacks = (AutoFallbackMode[])Enum.GetValues(typeof(AutoFallbackMode));

            foreach (int count in new[] { 0, 3, 4 })
            {
                var plain = Enumerable.Range(0, count)
                    .Select(i => Ohlc8Plain(i))
                    .ToList();
                var core = Enumerable.Range(0, count)
                    .Select(i => Ohlc8Core(i))
                    .ToList();
                CandleData[] plainArray = plain.ToArray();
                CoreCandleData[] coreArray = core.ToArray();

                foreach (var mode in modes)
                foreach (var rounding in roundings)
                foreach (var fallback in fallbacks)
                foreach (decimal fixedSize in new[] { 2.5m, 0m })
                foreach (decimal price in new[] { 0m, 100.5m })
                {
                    string key = $"{count}|{mode}|{rounding}|{fallback}|{fixedSize.ToString(CultureInfo.InvariantCulture)}|{price.ToString(CultureInfo.InvariantCulture)}";

                    lines.Add($"{key}|enum-plain|{Format(AutoBoxSizeCalculator.Calculate(mode, plain.Where(_ => true), fixedSize, AtrPeriod, AtrMultiplier, rounding, fallback, price, Percentage))}");
                    lines.Add($"{key}|list-plain|{Format(AutoBoxSizeCalculator.Calculate(mode, (IEnumerable<CandleData>)plain, fixedSize, AtrPeriod, AtrMultiplier, rounding, fallback, price, Percentage))}");
                    lines.Add($"{key}|span-plain|{Format(AutoBoxSizeCalculator.Calculate(mode, new ReadOnlySpan<CandleData>(plainArray), fixedSize, AtrPeriod, AtrMultiplier, rounding, fallback, price, Percentage))}");
                    lines.Add($"{key}|array-core|{Format(AutoBoxSizeCalculator.Calculate(mode, (IReadOnlyList<CoreCandleData>)coreArray, fixedSize, AtrPeriod, AtrMultiplier, rounding, fallback, price, Percentage))}");
                    lines.Add($"{key}|list-core|{Format(AutoBoxSizeCalculator.Calculate(mode, (IReadOnlyList<CoreCandleData>)core, fixedSize, AtrPeriod, AtrMultiplier, rounding, fallback, price, Percentage))}");
                    lines.Add($"{key}|span-core|{Format(AutoBoxSizeCalculator.Calculate(mode, new ReadOnlySpan<CoreCandleData>(coreArray), fixedSize, AtrPeriod, AtrMultiplier, rounding, fallback, price, Percentage))}");
                }
            }

            return lines;
        }

        [Fact]
        public void BoxSize_MatchesCapturedValues_ForEveryOverloadAndMode()
        {
            var actual = Capture();

            AssertMatches(Expected, actual, _output);
        }

